#!/usr/bin/env node
/**
 * Keeps the hand-written declarations (*.d.ts) in line with the runtime
 * modules.
 *
 * `exportChecksSource()` imports every module listed in package.json `files`,
 * reads its runtime export names and renders test/types/exports.ts, a type
 * test that fails `npm run typecheck` when a .d.ts declares a value export the
 * module does not have, or misses one it has. test/exports.test.js fails
 * `npm test` when that file is out of date (a module gained or lost an export).
 *
 * Usage: node scripts/export-names.mjs --write   (npm run types:exports)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const EXPORT_CHECKS_FILE = path.join(root, 'test', 'types', 'exports.ts');

/** The package's JavaScript modules (package.json `files`), e.g. ['command.js', ...]. */
export function packageModules() {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  return pkg.files.filter((f) => f.endsWith('.js') && !f.includes('/')).sort();
}

/** Runtime export names per module: { 'index.js': ['createApp', ...], ... }. */
export async function runtimeExports() {
  // the modules resolve the app root (and knexfile reads its config) on import
  process.env.AVEROA_ROOT ||= path.join(root, 'test', 'fixtures', 'app');
  process.env.NODE_ENV ||= 'test';
  const out = {};
  for (const file of packageModules()) {
    const mod = await import(pathToFileURL(path.join(root, file)).href);
    out[file] = Object.keys(mod).sort();
  }
  return out;
}

const alias = (file) => `m_${file.replace(/\.js$/, '').replace(/[^A-Za-z0-9]/g, '_')}`;

/** The source of test/types/exports.ts. */
export async function exportChecksSource() {
  const modules = await runtimeExports();
  const lines = [
    '// Generated by `npm run types:exports` from the runtime modules; do not edit.',
    '// `npm run typecheck` fails here when a .d.ts file declares a different set of',
    '// value exports than its module has at runtime: the error names the export.',
    '',
  ];
  for (const file of Object.keys(modules)) {
    lines.push(`import type * as ${alias(file)} from '../../${file}';`);
  }
  lines.push(
    '',
    '/** Exported at runtime but not declared. */',
    'type Undeclared<Runtime extends PropertyKey, Module> =',
    '  [Exclude<Runtime, keyof Module>] extends [never] ? true : Exclude<Runtime, keyof Module>;',
    '/** Declared but not exported at runtime. */',
    'type NotAtRuntime<Runtime extends PropertyKey, Module> =',
    '  [Exclude<keyof Module, Runtime>] extends [never] ? true : Exclude<keyof Module, Runtime>;',
  );
  for (const [file, names] of Object.entries(modules)) {
    const name = alias(file);
    const union = names.length ? names.map((n) => `'${n}'`).join(' | ') : 'never';
    lines.push(
      '',
      `// ${file}`,
      `type ${name}_runtime = ${union};`,
      `export const ${name}_undeclared: Undeclared<${name}_runtime, typeof ${name}> = true;`,
      `export const ${name}_not_at_runtime: NotAtRuntime<${name}_runtime, typeof ${name}> = true;`,
    );
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await exportChecksSource();
  if (process.argv.includes('--write')) {
    fs.writeFileSync(EXPORT_CHECKS_FILE, source);
    console.log(`${path.relative(root, EXPORT_CHECKS_FILE)} written.`);
  } else {
    process.stdout.write(source);
  }
}
